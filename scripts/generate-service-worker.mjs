import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = dirname(fileURLToPath(import.meta.url));
const distDir = join(rootDir, "..", "dist");
const swPath = join(distDir, "sw.js");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const fullPath = join(dir, entry.name);
      return entry.isDirectory() ? walk(fullPath) : fullPath;
    }),
  );

  return files.flat();
}

const files = (await walk(distDir)).filter((file) => file !== swPath);
const entries = await Promise.all(
  files.map(async (file) => {
    const contents = await readFile(file);
    const path = relative(distDir, file).split(sep).join("/");
    const hash = createHash("sha256").update(contents).digest("hex");

    return { path, hash };
  }),
);

entries.sort((a, b) => a.path.localeCompare(b.path));

const cacheHash = createHash("sha256")
  .update(entries.map((entry) => `${entry.path}:${entry.hash}`).join("\n"))
  .digest("hex")
  .slice(0, 12);

const urls = new Set();

for (const entry of entries) {
  const url = `/${entry.path}`;
  urls.add(url);

  if (url.endsWith("/index.html")) {
    urls.add(url.slice(0, -"index.html".length));
  }
}

const precacheUrls = [...urls].sort();

const serviceWorker = `/* Generated by scripts/generate-service-worker.mjs */
const CACHE_PREFIX = "fogop-precache-";
const CACHE_NAME = \`\${CACHE_PREFIX}${cacheHash}\`;
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE_NAME);
      await cache.addAll(
        PRECACHE_URLS.map((url) => new Request(url, { cache: "reload" })),
      );
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const cacheNames = await caches.keys();
      await Promise.all(
        cacheNames
          .filter((cacheName) => {
            return cacheName.startsWith(CACHE_PREFIX) && cacheName !== CACHE_NAME;
          })
          .map((cacheName) => caches.delete(cacheName)),
      );
      await self.clients.claim();
    })(),
  );
});

async function matchPrecache(cache, request) {
  const cached = await cache.match(request, { ignoreSearch: true });

  if (cached) {
    return cached;
  }

  if (request.mode !== "navigate") {
    return undefined;
  }

  const url = new URL(request.url);

  if (!url.pathname.endsWith("/")) {
    const normalized = await cache.match(\`\${url.pathname}/\`, {
      ignoreSearch: true,
    });

    if (normalized) {
      return normalized;
    }
  }

  return cache.match("/", { ignoreSearch: true });
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  const url = new URL(request.url);

  if (request.method !== "GET" || url.origin !== self.location.origin) {
    return;
  }

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE_NAME);
      const cached = await matchPrecache(cache, request);

      if (cached) {
        return cached;
      }

      try {
        const response = await fetch(request);

        if (response.ok && response.type === "basic") {
          await cache.put(request, response.clone());
        }

        return response;
      } catch {
        if (request.mode === "navigate") {
          return (await cache.match("/", { ignoreSearch: true })) || Response.error();
        }

        return Response.error();
      }
    })(),
  );
});
`;

await writeFile(swPath, serviceWorker);

console.log(
  `[pwa] Generated sw.js with ${precacheUrls.length} precached URLs (${cacheHash}).`,
);
